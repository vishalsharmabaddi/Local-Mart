-- V1: initial LocalMart schema.
-- RULE: never edit a migration after it has run anywhere. Add a new V2, V3... file instead.

CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255) NOT NULL,
    phone    VARCHAR(10)  NOT NULL,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_users_phone UNIQUE (phone),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'SHOP_OWNER', 'RIDER', 'ADMIN'))
);

CREATE TABLE shop (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255) NOT NULL,
    town     VARCHAR(255) NOT NULL,
    phone    VARCHAR(10)  NOT NULL,
    owner_id BIGINT       NOT NULL,
    CONSTRAINT fk_shop_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE product (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL,
    price   INTEGER      NOT NULL,
    stock   INTEGER      NOT NULL,
    version BIGINT       NOT NULL DEFAULT 0,
    shop_id BIGINT       NOT NULL,
    CONSTRAINT fk_product_shop FOREIGN KEY (shop_id) REFERENCES shop (id),
    CONSTRAINT ck_product_price_positive CHECK (price > 0),
    CONSTRAINT ck_product_stock_not_negative CHECK (stock >= 0)   -- last line of defense
);

CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT                   NOT NULL,
    shop_id      BIGINT                   NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    total_amount INTEGER                  NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version      BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_orders_shop FOREIGN KEY (shop_id) REFERENCES shop (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('PLACED', 'ACCEPTED', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED'))
);

CREATE TABLE order_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT       NOT NULL,
    product_id   BIGINT       NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    unit_price   INTEGER      NOT NULL,
    quantity     INTEGER      NOT NULL,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_order_item_quantity_positive CHECK (quantity > 0)
);

-- Postgres does NOT index foreign keys automatically. These match the queries our app runs.
CREATE INDEX idx_shop_owner           ON shop (owner_id);
CREATE INDEX idx_product_shop         ON product (shop_id);                    -- products of a shop
CREATE INDEX idx_orders_customer_date ON orders (customer_id, created_at DESC); -- "my orders", newest first
CREATE INDEX idx_orders_shop_date     ON orders (shop_id, created_at DESC);     -- "shop orders", newest first
CREATE INDEX idx_order_item_order     ON order_item (order_id);                 -- items of an order
